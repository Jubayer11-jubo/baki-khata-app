/**
 * Professional Bengali reminder generator for WhatsApp
 */
export function generateWhatsAppReminder(params: {
  customerName: string;
  dueAmount: number;
  shopName: string;
  shopPhone?: string;
  dueDate?: string;
  bkashNumber?: string;
  nagadNumber?: string;
}): string {
  const formattedAmount = `৳${params.dueAmount.toLocaleString('en-IN')}`;
  
  let paymentInfo = '';
  if (params.bkashNumber || params.nagadNumber) {
    paymentInfo = '\n\nপেমেন্ট পাঠানোর মাধ্যম:';
    if (params.bkashNumber) paymentInfo += `\n- বিকাশ (Personal): ${params.bkashNumber}`;
    if (params.nagadNumber) paymentInfo += `\n- নগদ: ${params.nagadNumber}`;
  }

  let dateInfo = '';
  if (params.dueDate) {
    dateInfo = `\nপরিশোধের নির্ধারিত তারিখ: ${params.dueDate}`;
  }

  return `আসসালামু আলাইকুম ${params.customerName} ভাই,

আপনার কাছে আমাদের "${params.shopName}"-এর মোট ${formattedAmount} টাকা বাকি রয়েছে।${dateInfo}

সম্ভব হলে সুবিধামতো পরিশোধ করার আন্তরিক অনুরোধ রইলো।${paymentInfo}

ধন্যবাদ।
${params.shopName}
${params.shopPhone ? `মোবাইল: ${params.shopPhone}` : ''}`;
}

/**
 * Short SMS template generator
 */
export function generateSMSReminder(params: {
  customerName: string;
  dueAmount: number;
  shopName: string;
}): string {
  const formattedAmount = `৳${params.dueAmount.toLocaleString('en-IN')}`;
  return `আপনার কাছে ${params.shopName}-এর ${formattedAmount} টাকা বাকি আছে। সুবিধামতো পরিশোধের অনুরোধ রইলো। ধন্যবাদ।`;
}
